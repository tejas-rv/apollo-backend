package com.apollo.elevator.documents.service;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import com.apollo.elevator.customer.repository.CustomerRepository;
import com.apollo.elevator.documents.model.dto.BillRequest;
import com.apollo.elevator.documents.model.enums.DocumentType;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;

class DocumentServiceTest {

    private DocumentService documentService;
    private PdfTemplateService pdfTemplateService;

    @BeforeEach
    void setUp() {
        pdfTemplateService = mock(PdfTemplateService.class);
        when(pdfTemplateService.renderToPdf(any(), any(Map.class))).thenReturn("pdf-bytes".getBytes());
        documentService = new DocumentService(
                mock(CustomerRepository.class),
                pdfTemplateService,
                mock(com.apollo.elevator.documents.service.UpiQrCodeService.class)
        );
    }

    @Test
    void generateBillPdfAcceptsDisplayStyleQuantityFromAutoGeneratedPreview() {
        // buildBillPreview's default quantity is "01 No" (a unit label, not a plain number) —
        // generateBillPdf must still accept it when chaining preview -> generate automatically.
        BillRequest billRequest = bill(18.0, List.of(
                new BillRequest.BillLineItem(1, "Periodical Maintenance", "99611", "01 No", 3900.0, 3900.0)));

        assertDoesNotThrow(() -> documentService.generateBillPdf(DocumentType.GST_BILL, billRequest));
    }

    @Test
    void editedBillRecomputesLineAmountsAndSplitsGstEvenly() {
        // Client sent stale amounts (quantity/rate were edited but amount was not updated).
        BillRequest billRequest = bill(18.0, List.of(
                new BillRequest.BillLineItem(7, "Periodical Maintenance", "99611", "2 Nos", 1500.0, 1500.0),
                new BillRequest.BillLineItem(9, "Spare part", "8431", "3", 333.33, 0.0)));

        documentService.generateBillPdf(DocumentType.GST_BILL, billRequest);
        Map<String, Object> vars = capturedVariables();

        @SuppressWarnings("unchecked")
        List<BillRequest.BillLineItem> items = (List<BillRequest.BillLineItem>) vars.get("lineItems");
        assertEquals(3000.0, items.get(0).amount());
        assertEquals(999.99, items.get(1).amount());
        assertEquals(1, items.get(0).slNo());
        assertEquals(2, items.get(1).slNo());

        assertEquals(3999.99, vars.get("totalBeforeTax"));
        assertEquals(360.0, vars.get("sgstAmount"));
        assertEquals(360.0, vars.get("cgstAmount"));
        assertEquals(4719.99, vars.get("totalAfterTax"));

        BillRequest.BillDetails details = (BillRequest.BillDetails) vars.get("bill");
        assertEquals(9.0, details.sgstPercentage());
        assertEquals(9.0, details.cgstPercentage());
        assertEquals("9%", vars.get("halfGstRateLabel"));
    }

    @Test
    void oddGstRateSplitsIntoHalfPercentLabels() {
        documentService.generateBillPdf(DocumentType.GST_BILL, bill(5.0, List.of(
                new BillRequest.BillLineItem(1, "Service", "99611", "1", 1000.0, 1000.0))));
        Map<String, Object> vars = capturedVariables();

        assertEquals("2.5%", vars.get("halfGstRateLabel"));
        assertEquals(1050.0, vars.get("totalAfterTax"));
    }

    @SuppressWarnings("unchecked")
    private Map<String, Object> capturedVariables() {
        ArgumentCaptor<Map<String, Object>> captor = ArgumentCaptor.forClass(Map.class);
        verify(pdfTemplateService).renderToPdf(eq("pdf/gst-bill"), captor.capture());
        return captor.getValue();
    }

    private static BillRequest bill(double gst, List<BillRequest.BillLineItem> items) {
        return new BillRequest(
                BillRequest.BillingEntity.APOLLO_ELEVATOR,
                new BillRequest.BillDetails(
                        "0111", "27/09/2026", "Karnataka", "560058", "9999999999",
                        "ABPFA4107Q", "29ABPFA4107Q1ZU", gst, null, null
                ),
                new BillRequest.BillToParty("Tejas V", "Address", null, null, null, null, "Karnataka"),
                items
        );
    }
}